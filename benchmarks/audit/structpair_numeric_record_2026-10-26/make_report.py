"""Generates REPORT.md from results/btk2_numeric_record_regression.json (no number is typed here).

    .venv/bin/python benchmarks/audit/structpair_numeric_record_2026-10-26/make_report.py
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
d = json.loads((HERE / "results/btk2_numeric_record_regression.json").read_text())
rows = []
for cl in d["table_cells"]:
    for tag in ("base", "moved"):
        c = cl[tag]
        rows.append([f"{cl['metric']} at position {cl['position']} ({cl['A_residue']}/{cl['B_residue']}), {cl['unit']}", "original inputs" if tag == "base" else "transformed inputs",
                     repr(c["computed"]), c["csv"], repr(c["record"]), "yes" if c["computed"] == c["record"] else "NO"])
    rows.append(["", "difference original vs transformed", "", f"{cl['difference_csv']!r}", f"{cl['difference_record']!r}", ""])
head = ["value", "input", "computed (float64, before formatting)", "rounded CSV (6 significant figures)", "precision-preserving record", "record equals computed"]
tab = "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(r) + " |" for r in rows])
w = d["worst_original_vs_transformed"]
text = f"""# structpair numeric_record.json (KNOWN_ISSUES m13b): generated regression report

Generated by `make_report.py` from `results/btk2_numeric_record_regression.json`. **Engineering regression on the original and rigidly transformed BTK-2 inputs
of the KIN-PAIR-1 supplement; KIN-PAIR-1 is not reclassified and this is not a new evaluation.**

{tab}

*Table 1. Purpose: show the same value as computed, as rounded in `windows.csv`, and as preserved in `numeric_record.json`, for the two values that matter in the BTK-2
case (the largest CSV difference and the largest difference of the record) between the original and the transformed inputs. Limitation: the record preserves the computed
float64 values exactly; it does not improve experimental accuracy and does not remove the float32 coordinate step of the Cα adapter, which is what the remaining
difference of {w['in_the_record']['difference']:.1e} reflects. Source: `results/btk2_numeric_record_regression.json`.*

- Original and transformed run: record equals the pre-format computed values exactly for all {d['base']['n_values']} and {d['moved']['n_values']} values (`==`, not a tolerance); verification of the manifest, including `numeric_record.json`, passes.
- Default outputs (`windows.csv`, `residues.csv`, `exclusions.csv`) with the export enabled are byte-identical to the earlier runs without it.
- The largest original-vs-transformed difference is {w['in_the_record']['difference']:.1e} in the record ({w['in_the_record']['metric']}, position {w['in_the_record']['position']}) and {w['in_the_csv']['difference']!r} in the CSV ({w['in_the_csv']['metric']}, position {w['in_the_csv']['position']}): rounding to six significant figures turned a smaller difference into one CSV quantum.
- The independent float64 recomputation from the PDB text (earlier diagnosis) differs by {d['independent_float64_from_text_max_deviation_earlier_diagnosis']:.1e}; the float32 coordinate spacing at the largest transformed coordinate is {d['float32_spacing_at_largest_transformed_coordinate']:.1e} Å. The remaining difference in the record is that float32 step, as before; it is not removed by the record.
"""
(HERE / "REPORT.md").write_text(text)
print("wrote REPORT.md")
