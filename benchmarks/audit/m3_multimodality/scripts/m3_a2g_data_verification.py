def verify_exact_family():
    """Analyze exact-family convergence audit."""
    csv_path = results_dir / "m3_a2g_exact_family_convergence.csv"
    with open(csv_path) as f:
        reader = csv.DictReader(f)
        rows = list(reader)
    
    total = len(rows)
    converged = sum(1 for r in rows if r['converged'] == 'True')
    
    # By F
    by_F = defaultdict(lambda: {'total': 0, 'converged': 0})
    for r in rows:
        F = int(r['F'])
        by_F[F]['total'] += 1
        if r['converged'] == 'True':
            by_F[F]['converged'] += 1
    
    # Configurations with <20% convergence
    configs = defaultdict(list)
    for r in rows:
        key = f"{r['q']},{r['kappa']},{r['F']}"
        configs[key].append(r['converged'] == 'True')
    
    low_conv_configs = []
    zero_conv_configs = []
    for config, conv_list in sorted(configs.items()):
        rate = sum(conv_list) / len(conv_list)
        if rate < 0.20:
            low_conv_configs.append((config, rate, sum(conv_list), len(conv_list)))
        if rate == 0:
            zero_conv_configs.append(config)
    
    return {
        'total_fits': total,
        'converged': converged,
        'rate': converged / total,
        'by_F': dict(by_F),
        'low_conv_configs': low_conv_configs,
        'zero_conv_configs': zero_conv_configs,
        'num_low_conv': len(low_conv_configs),
        'num_zero_conv': len(zero_conv_configs)
    }

