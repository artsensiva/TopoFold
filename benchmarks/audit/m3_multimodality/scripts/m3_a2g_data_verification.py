def compute_input_hashes():
    """Compute SHA-256 hashes of input CSV/TXT files."""
    hashes = {}
    for csv_file in sorted(results_dir.glob("m3_a2g_*.csv")):
        with open(csv_file, 'rb') as f:
            file_hash = hashlib.sha256(f.read()).hexdigest()
        hashes[csv_file.name] = file_hash

    txt_file = results_dir / "m3_a2g_trajectories.txt"
    if txt_file.exists():
        with open(txt_file, 'rb') as f:
            hashes[txt_file.name] = hashlib.sha256(f.read()).hexdigest()

    return hashes

