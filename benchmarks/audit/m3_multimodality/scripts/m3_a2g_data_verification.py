def verify_ninit_sensitivity():
    """Analyze n_init sensitivity."""
    csv_path = results_dir / "m3_a2g_ninit_sensitivity.csv"
    with open(csv_path) as f:
        reader = csv.DictReader(f)
        rows = list(reader)
    
    by_case = defaultdict(list)
    for r in rows:
        by_case[r['case']].append({
            'n_init': int(r['n_init']),
            'converged': int(r['n_converged']),
            'total': int(r['n_init']),
            'best_loglik': float(r['best_loglik']),
            'spread_range': float(r['spread_range'])
        })
    
    # Check for wrapped_1.0 loglik differences
    wrapped_data = by_case.get('wrapped_1.0', [])
    if len(wrapped_data) >= 2:
        loglik_diff = abs(wrapped_data[0]['best_loglik'] - wrapped_data[1]['best_loglik'])
    else:
        loglik_diff = None
    
    return {
        'by_case': dict(by_case),
        'wrapped_1.0_loglik_diff': loglik_diff
    }

def verify_trajectories():
    """Parse trajectory blocks and count actual iteration state records."""
    txt_path = results_dir / "m3_a2g_trajectories.txt"
    with open(txt_path) as f:
        content = f.read()

    # Parse blocks separated by "Case:"
    blocks = content.split('Case: ')[1:]  # Skip header before first case

    trajectory_counts = {}
    total_iterations = 0

    for block in blocks:
        lines = block.strip().split('\n')
        if not lines:
            continue

        # First line is case name
        case_name = lines[0].strip()

        # Find CSV header and count numeric records after it
        in_csv = False
        iter_count = 0

        for line in lines:
            stripped = line.strip()
            if stripped.startswith('iter,loglik'):
                in_csv = True
                continue

            if in_csv and stripped and stripped[0].isdigit():
                iter_count += 1

        trajectory_counts[case_name] = iter_count
        total_iterations += iter_count

    return {
        'total_blocks': len(blocks),
        'iteration_records_total': total_iterations,
        'per_trajectory': trajectory_counts
    }

def validate_csv_schema(csv_file, expected_columns):
    """Validate CSV schema matches expected columns."""
    with open(csv_file) as f:
        reader = csv.DictReader(f)
        actual_columns = set(reader.fieldnames or [])

    expected_set = set(expected_columns)
    missing = expected_set - actual_columns
    extra = actual_columns - expected_set

    return {
        'valid': len(missing) == 0 and len(extra) == 0,
        'missing': sorted(missing),
        'extra': sorted(extra),
        'actual_columns': sorted(actual_columns)
    }

