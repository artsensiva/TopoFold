# Tracked artifacts outside the M3 directory that must also be preserved
# (relative to the M3 directory).
EXTERNAL_PROTECTED = ['../v0.8.3-corrections-historical.patch']

_ROW_RE = re.compile(r'^\|\s*`([^`]+)`\s*\|.*\|\s*`([0-9a-f]{64})`\s*\|\s*$')


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(65536), b''):
            h.update(chunk)
    return h.hexdigest()


def _ignored(rel):
    parts = Path(rel).parts
    return ('__pycache__' in parts or '.pytest_cache' in parts or rel.endswith('.pyc'))


def disk_inventory(base_dir=BASE_DIR):
    """All files in the M3 directory except MANIFEST.md and Python caches."""
    base_dir = Path(base_dir)
    out = set()
    for p in base_dir.rglob('*'):
        if p.is_file():
            rel = p.relative_to(base_dir).as_posix()
            if rel != MANIFEST_NAME and not _ignored(rel):
                out.add(rel)
    return out


def _git(base_dir, *args, binary=False):
    res = subprocess.run(['git', *args], cwd=base_dir, capture_output=True, check=True)
    return res.stdout if binary else res.stdout.decode()


def tracked_files(base_dir=BASE_DIR):
    return {line for line in _git(base_dir, 'ls-files', '.').splitlines() if line}


def tracked_at(base_dir, rev):
    return {line for line in _git(base_dir, 'ls-tree', '-r', '--name-only', rev, '.').splitlines()
            if line}


def parse_manifest(text):
    """Return [(path, sha256, line_number)] for every inventory table row."""
    entries = []
    for ln, line in enumerate(text.splitlines(), start=1):
        m = _ROW_RE.match(line.strip())
        if m:
            entries.append((m.group(1), m.group(2), ln))
    return entries


def check_manifest(base_dir=BASE_DIR, manifest_path=None, classification=CLASSIFICATION):
    """Inventory coverage, duplicates and checksum comparison (read-only)."""
    base_dir = Path(base_dir)
    manifest_path = Path(manifest_path) if manifest_path else base_dir / MANIFEST_NAME
    entries = parse_manifest(manifest_path.read_text())
    on_disk = disk_inventory(base_dir)

    seen, duplicates = {}, []
    for path, digest, ln in entries:
        if path in seen:
            duplicates.append(f"{path} (lines {seen[path]} and {ln})")
        else:
            seen[path] = ln
    listed = {p for p, _, _ in entries}
    if MANIFEST_NAME in listed:
        duplicates.append(f"{MANIFEST_NAME} must not hash itself")

    mismatches, missing_on_disk = [], []
    for path, digest, ln in entries:
        f = base_dir / path
        if not f.is_file():
            missing_on_disk.append(path)
        elif sha256_file(f) != digest:
            mismatches.append(f"{path} (line {ln})")

    report = {
        'entries': len(entries),
        'files_on_disk': len(on_disk),
        'duplicate_entries': duplicates,
        'omitted_from_manifest': sorted(on_disk - listed),
        'listed_but_missing': sorted(missing_on_disk),
        'checksum_mismatches': mismatches,
        'unclassified_files': sorted(on_disk - set(classification)),
        'classified_but_missing': sorted(set(classification) - on_disk),
    }
    report['passed'] = not any(report[k] for k in [
        'duplicate_entries', 'omitted_from_manifest', 'listed_but_missing',
        'checksum_mismatches', 'unclassified_files', 'classified_but_missing'])
    return report


def compare_protected(base_dir=BASE_DIR, rev=BASELINE_REV, editable=EDITABLE,
                      external=EXTERNAL_PROTECTED):
    """Byte comparison of every protected artifact against the baseline revision."""
    base_dir = Path(base_dir)
    prefix = _git(base_dir, 'rev-parse', '--show-prefix').strip()
    paths = sorted(p for p in tracked_at(base_dir, rev) if p not in editable) + list(external)
    changed, missing, identical = [], [], 0
    for rel in paths:
        repo_path = posixpath.normpath(posixpath.join(prefix, rel))
        current = base_dir / rel
        if not current.is_file():
            missing.append(rel)
            continue
        baseline = _git(base_dir, 'show', f'{rev}:{repo_path}', binary=True)
        if hashlib.sha256(baseline).hexdigest() != sha256_file(current):
            changed.append(rel)
        else:
            identical += 1
    return {'rev': rev, 'protected': len(paths), 'identical': identical,
            'changed': changed, 'missing': missing, 'passed': not changed and not missing}


def render_inventory(base_dir=BASE_DIR):
    base_dir = Path(base_dir)
    lines = [BEGIN_MARKER, '']
    for category in CATEGORY_ORDER:
        paths = sorted(p for p, (c, _) in CLASSIFICATION.items() if c == category)
        if not paths:
            continue
        lines += [f'### {category}', '', '| Path | Note | SHA-256 |', '|------|------|---------|']
        for p in paths:
            lines.append(f"| `{p}` | {CLASSIFICATION[p][1]} | `{sha256_file(base_dir / p)}` |")
        lines.append('')
    lines.append(END_MARKER)
    return '\n'.join(lines)


def update_manifest(base_dir=BASE_DIR):
    path = Path(base_dir) / MANIFEST_NAME
    text = path.read_text()
    if BEGIN_MARKER not in text or END_MARKER not in text:
        raise SystemExit(f"{MANIFEST_NAME}: inventory markers not found")
    head, rest = text.split(BEGIN_MARKER, 1)
    _, tail = rest.split(END_MARKER, 1)
    path.write_text(head + render_inventory(base_dir) + tail)


def main(argv=None):
    parser = argparse.ArgumentParser(description='M3 manifest checks')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='verify (default)')
    mode.add_argument('--print', action='store_true', help='print current hashes')
    mode.add_argument('--render', action='store_true', help='print inventory table')
    mode.add_argument('--update', action='store_true', help='rewrite inventory in MANIFEST.md')
    parser.add_argument('--rev', default=BASELINE_REV, help='baseline revision for preservation')
    args = parser.parse_args(argv)

    if args.print:
        for category in CATEGORY_ORDER:
            print(f"\n{category}:")
            for p in sorted(p for p, (c, _) in CLASSIFICATION.items() if c == category):
                print(f"  {sha256_file(BASE_DIR / p)}  {p}")
        return 0
    if args.render:
        print(render_inventory())
        return 0
    if args.update:
        update_manifest()
        print(f"Updated inventory in {MANIFEST_NAME}")
        return 0

    tracked = tracked_files()
    missing_tracked = sorted(p for p in tracked if not (BASE_DIR / p).is_file())
    m = check_manifest()
    p = compare_protected(rev=args.rev)
    print(f"Manifest: {m['entries']} entries, {m['files_on_disk']} files on disk "
          f"(excluding {MANIFEST_NAME} and caches)")
    for key in ['duplicate_entries', 'omitted_from_manifest', 'listed_but_missing',
                'checksum_mismatches', 'unclassified_files', 'classified_but_missing']:
        print(f"  {key}: {len(m[key])}" + (f" {m[key]}" if m[key] else ''))
    print(f"  tracked files missing on disk: {len(missing_tracked)}"
          + (f" {missing_tracked}" if missing_tracked else ''))
    print(f"Protected vs {p['rev'][:12]}: {p['identical']}/{p['protected']} identical; "
          f"changed={p['changed']} missing={p['missing']}")
    ok = m['passed'] and p['passed'] and not missing_tracked
    print('PASS' if ok else 'FAIL')
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
