#!/usr/bin/env python3
"""WP-D AdK descriptive report. Every number is read from the results JSON (AGENTS.md rule 3).

Run: build/venv/bin/python -B make_report.py
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / 'results'
IN = RES / 'wpd_adk_THIRD_PARTY_MD_DERIVATIVE_retrieval.json'
PROV = RES / 'wpd_adk_THIRD_PARTY_MD_DERIVATIVE_provenance.json'
OUT = HERE / 'REPORT_ADK.md'
METHODS = ('M1', 'M2', 'B1', 'B2', 'B3', 'C1')
NAMES = {'M1': 'ordered chord D_ch (τ)', 'M2': 'ordered circular D_circ (τ)', 'B1': 'Cα–Cα distances (q−p ≥ 2)',
         'B2': 'window Cα RMSD (Horn)', 'B3': 'κ block D_κ', 'C1': 'scalar circular-mean comparator'}


def f(x, d=3):
    return '—' if x is None else f'{x:.{d}f}'


def mi(s, d=3):
    if s['median'] is None:
        return '—'
    return f"{f(s['median'], d)} [{f(s['q25'], d)}, {f(s['q75'], d)}]"


def e(x):
    return '—' if x is None else f'{x:.1e}'


def main():
    r = json.loads(IN.read_text())
    p = json.loads(PROV.read_text())
    meta, S = r['_meta'], r['summary']
    L = []
    w = L.append
    w('# WP-D AdK development tier: Cα-only local retrieval vs full-backbone φ/ψ target')
    w('')
    w(f"**{meta['label']}.** {meta['data']}. {meta['tier']}.")
    w('')
    w(f"Protocol `{meta['protocol']}` (SHA-256 `{meta['protocol_sha256'][:16]}…`, frozen before any feature or "
      f"score was computed). Generated by `make_report.py` from `{IN.name}`; run started "
      f"{meta['started_utc']}, wall time {meta['wall_seconds']} s. Harness tests before the run: "
      f"exit code {p['tests']['exit_code']} (`{p['tests']['summary']}`).")
    w('')
    w('Values are medians across windows of per-window query means, with the interquartile range in brackets. '
      'Higher overlap is better; lower regret is better. Normalized regret is 0 for target-optimal retrieval '
      'and 1 for random retrieval in expectation. Trajectories and window sizes are never pooled. '
      'AdK is descriptive only: no retain/reject decision is taken (protocol §7).')
    w('')
    w('## 1. Inputs, binding identity and numerical checks')
    w('')
    b = p['inputs']['binding']
    w(f"- Binding: `{b['wheel']}`; loaded extension SHA-256 `{b['extension_sha256'][:16]}…` equals the WP-A "
      f"extension: {b['equals_wpa_extension']}; {len(b['production_sources_sha256'])} production sources equal "
      f"the WP-A record: {b['production_sources_equal_wpa']}.")
    w(f"- Raw files bound to WP-B G0 by SHA-256: {len(p['inputs']['raw_sha256'])} files; eligibility artifact and "
      'protocol match the freeze record.')
    w(f"- Versions: Python {p['versions']['python']}, NumPy {p['versions']['numpy']}, MDAnalysis "
      f"{p['versions']['mdanalysis']}, SciPy {p['versions']['scipy']}.")
    w('')
    w('| Check | open_start | closed_start |')
    w('|---|---|---|')
    T = r['trajectories']
    o, c = T['open_start'], T['closed_start']

    def row(name, fn):
        w(f'| {name} | {fn(o)} | {fn(c)} |')
    row('Frames', lambda t: t['n_frames'])
    row('Query / gap / database (half-open frame ranges)',
        lambda t: ' / '.join(f"{a}–{b_}" for a, b_ in t['splits_half_open'].values()))
    row('Cadence (ps, unique values)', lambda t: t['cadence_ps_unique'])
    row('Frames checked: binding τ/κ vs NumPy', lambda t: t['reference_check']['frames_checked'])
    row('Max circular τ difference (rad)', lambda t: e(t['reference_check']['max_tau_circ_diff']))
    row('Max κ difference (rad)', lambda t: e(t['reference_check']['max_kappa_diff']))
    row('τ positions skipped as degenerate in the check', lambda t: t['reference_check']['tau_positions_skipped_degenerate'])
    row('Binding failures (frames)', lambda t: t['binding_failure_frames'])
    row('Frames changed by periodic reconstruction (Cα / backbone)',
        lambda t: f"{t['whole_reconstruction']['ca_whole_changed_frames']} / "
                  f"{t['whole_reconstruction']['bb_whole_changed_frames']}")
    row('Frames changed by float32 round trip', lambda t: t['whole_reconstruction']['float32_roundtrip_changed_frames'])
    row('Min sin of Cα virtual bond angle', lambda t: f(t['min_sin_ca_vertex']))
    row('Min sin of backbone bond angle', lambda t: f(t['min_sin_backbone']))
    row('Max backbone bond after reconstruction (Å)', lambda t: f(t['backbone_bond_max_A_after_whole']))
    row('cis peptides (frame × bond, |ω| < π/2)', lambda t: t['cis_peptide_frame_bonds'])
    row('Bonds r→r+1 ever cis', lambda t: t['cis_peptide_bonds_residue_r_to_r_plus_1'])
    hk = {k: v['horn_kabsch_max_abs_diff_A'] for k, v in S.items()}
    w('')
    w('Horn vs Kabsch (B2), max |difference| over sampled pairs, per cell: '
      + '; '.join(f'{k} {e(v)} Å' for k, v in hk.items()) + '.')
    w('')
    w('## 2. Coverage, exclusions and numerical failures')
    w('')
    w('| Cell | Windows (defined) | Undefined windows | Valid query×window | Valid db×window | Excluded query (bind / degCα / degT / break) | Excluded db | Regret rounded to 0 (all methods, k) | Regret numerical failures |')
    w('|---|---|---|---|---|---|---|---|---|')
    for key, cell in S.items():
        cv = cell['coverage']
        xq = ' / '.join(str(v) for v in cv['excluded_query'].values())
        xd = ' / '.join(str(v) for v in cv['excluded_db'].values())
        rounded = sum(cell['methods'][m][f'k{k}']['total_n_regret_rounded_to_zero'] for m in METHODS for k in (1, 10))
        fails = sum(cell['methods'][m][f'k{k}']['total_n_regret_numerical_failures'] for m in METHODS for k in (1, 10))
        w(f"| {key} | {cell['n_windows']} | {len(cell['undefined_windows'])} | {cv['query_frame_windows_valid']} | "
          f"{cv['db_frame_windows_valid']} | {xq} | {xd} | {rounded} | {fails} |")
    w('')
    w('**C1 conditioning (A1).** R is the resultant length of the window\'s τ; R < 0.1 is ill-conditioned.')
    w('')
    w('| Cell | R min | median of per-window 5 % R | median of per-window median R | Ill-conditioned fraction (pooled) | Ill query frames | Ill db frames | Windows with any ill frame | C1 undefined queries (k=1 / k=10) |')
    w('|---|---|---|---|---|---|---|---|---|')
    for key, cell in S.items():
        cc = cell['c1_conditioning']
        c1 = cell['methods']['C1']
        w(f"| {key} | {f(cc['R_min'])} | {f(cc['R_p05_median_across_windows'])} | "
          f"{f(cc['R_median_median_across_windows'])} | {f(cc['ill_fraction_pooled'], 4)} | {cc['n_query_ill_total']} | "
          f"{cc['n_db_ill_total']} | {cc['windows_with_any_ill']} | {c1['k1']['total_n_queries_undefined']} / "
          f"{c1['k10']['total_n_queries_undefined']} |")
    w('')
    w('Normalized-regret undefined queries (constant target, A3) and boundary-tie queries, totals over windows:')
    w('')
    w('| Cell | ' + ' | '.join(f'{m} undef. k=10' for m in METHODS) + ' | ' + ' | '.join(f'{m} ties k=10' for m in METHODS) + ' |')
    w('|---|' + '---|' * (2 * len(METHODS)))
    for key, cell in S.items():
        w(f'| {key} | ' + ' | '.join(str(cell['methods'][m]['k10']['total_n_norm_undefined']) for m in METHODS) + ' | '
          + ' | '.join(str(cell['methods'][m]['k10']['total_n_queries_with_boundary_ties']) for m in METHODS) + ' |')
    w('')
    for key, cell in S.items():
        w(f'## 3.{list(S).index(key) + 1} {key}')
        w('')
        rr = cell['random_reference']
        w(f"Target spread (median T(q,d) per window, rad): {mi(cell['target_spread_median_across_windows'])}. "
          f"Random reference: overlap@1 {mi(rr['k1']['overlap'], 4)}, overlap@10 {mi(rr['k10']['overlap'], 4)}; "
          f"raw regret@1 {mi(rr['k1']['raw_regret'])}, raw regret@10 {mi(rr['k10']['raw_regret'])} rad; "
          'normalized regret 1.')
        w('')
        w('| Method | overlap@1 | overlap@10 | regret@1 (rad) | regret@10 (rad) | norm. regret@1 | norm. regret@10 | Spearman ρ |')
        w('|---|---|---|---|---|---|---|---|')
        for m in METHODS:
            cm = cell['methods'][m]
            w(f"| {m} {NAMES[m]} | {mi(cm['k1']['mean_overlap'], 4)} | {mi(cm['k10']['mean_overlap'], 4)} | "
              f"{mi(cm['k1']['mean_regret'])} | {mi(cm['k10']['mean_regret'])} | {mi(cm['k1']['mean_norm_regret'])} | "
              f"{mi(cm['k10']['mean_norm_regret'])} | {mi(cm['spearman'])} |")
        w('')
        bounds = cell['tercile_spread_bounds']
        w('By tercile of target spread (rad bounds: '
          + '; '.join(f'T{t + 1} {f(b_[0])}–{f(b_[1])}' if b_ else f'T{t + 1} —' for t, b_ in enumerate(bounds))
          + '); medians across windows:')
        w('')
        w('| Method | overlap@10 T1 / T2 / T3 | norm. regret@10 T1 / T2 / T3 | Spearman T1 / T2 / T3 |')
        w('|---|---|---|---|')
        for m in METHODS:
            cm = cell['methods'][m]
            ov = ' / '.join(f(t['median'], 4) for t in cm['k10']['mean_overlap_by_spread_tercile'])
            nr = ' / '.join(f(t['median']) for t in cm['k10']['mean_norm_regret_by_spread_tercile'])
            sp = ' / '.join(f(t['median']) for t in cm['spearman_by_spread_tercile'])
            w(f'| {m} | {ov} | {nr} | {sp} |')
        w('')
    w('## 4. Descriptive observations (computed orderings, no decision)')
    w('')
    for key, cell in S.items():
        ms = cell['methods']
        rank = sorted(METHODS, key=lambda m: -(ms[m]['k10']['mean_overlap']['median'] or -1))
        nrank = sorted(METHODS, key=lambda m: (ms[m]['k10']['mean_norm_regret']['median']
                                               if ms[m]['k10']['mean_norm_regret']['median'] is not None else 9))
        rnd = cell['random_reference']['k10']['overlap']['median']
        w(f"- **{key}**: order of unrounded median overlap@10 (high first): {', '.join(rank)}; order of unrounded "
          f"median normalized regret@10 (low first): {', '.join(nrank)}. Adjacent entries may differ by less than "
          f"the displayed precision and IQRs overlap; the order is not a test. Methods whose median normalized "
          f"regret@10 is below the random reference of 1: "
          f"{[m for m in METHODS if (ms[m]['k10']['mean_norm_regret']['median'] or 9) < 1]}. "
          f"Highest median overlap@10 divided by random overlap@10: "
          f"{f(ms[rank[0]]['k10']['mean_overlap']['median'] / rnd, 1)}.")
    w('')
    w('## 5. Limitations')
    w('')
    w('- AdK is a development tier on two trajectories of one protein, chosen and inspected in WP-B; results '
      'are descriptive and cannot support claims about other proteins.')
    w('- Query and database frames come from the same trajectory separated by a gap; they are not independent '
      'and the runs drift (WP-B), so query and database frames may sample different regimes (protocol §5).')
    w('- Medians and IQRs are across windows, which overlap and are correlated; no interval or test is reported.')
    w('- The φ/ψ target is a reference description of local backbone conformation, not ground truth for function. '
      'Cα-only inputs do not contain peptide-plane orientation; how much of the φ/ψ variation they can recover '
      'is what is measured here, not assumed.')
    w('- xtc coordinates are quantized to 0.01 Å; all methods receive identical values (A2).')
    w('- B3 uses the production κ (turning angle, π minus the virtual bond angle); the RMS difference is identical '
      'for either convention.')
    w('')
    w('## 6. Interpretation notes (editorial closeout, added after execution; results unchanged)')
    w('')
    w('These notes were added after the run, without rerunning; the results and provenance files are unchanged '
      '(see `results/wpd_adk_editorial_log.json`).')
    w('')
    w('**C1 is compared on a different, conditional coverage.** C1 has no result for queries whose window mean is '
      'ill-conditioned (R < 0.1), and database frames with R < 0.1 are ranked last as +∞ (A1). Its aggregates '
      'therefore average over a subset of queries and rank a reduced effective candidate set, while M1, M2, B1, '
      'B2 and B3 use all valid queries and candidates. The C1 rows describe performance *conditional on a '
      'well-conditioned mean*; they are not a like-for-like comparison with the other methods. The random '
      'reference uses all database frames. Share of valid queries with a C1 result at k = 10:')
    w('')
    w('| Cell | Queries with C1 result / valid queries | Ill-conditioned database frames (window × frame) |')
    w('|---|---|---|')
    for key, cell in S.items():
        c1 = cell['methods']['C1']['k10']
        n_all = c1['total_n_queries_valid'] + c1['total_n_queries_undefined']
        w(f"| {key} | {c1['total_n_queries_valid']} / {n_all} ({f(c1['total_n_queries_valid'] / n_all, 4)}) | "
          f"{cell['c1_conditioning']['n_db_ill_total']} |")
    w('')
    w('**The cis-peptide count does not establish the dihedral sign convention.** The criterion |ω| < π/2 is '
      'invariant to the sign of ω, so the single cis bond observed (Phe86–Pro87, matching the CISPEP records of '
      '4AKE and 1AKE) is consistent with the backbone atom mapping but says nothing about the sign of φ, ψ or τ. '
      'The sign convention rests on the WP-A IUPAC reference checks and on `test_dihedral_known_values` in '
      '`test_wpd.py`. An earlier chat summary of this run stated otherwise; that statement was wrong and is '
      'withdrawn.')
    w('')
    w('**Competing methods.** M1/M2 (ordered τ), B1 (Cα–Cα distances), B2 (window Cα RMSD) and B3 (κ) remain '
      'competing candidates for the held-out tier. The AdK orderings above are descriptive, from one protein, and '
      'do not pre-select a winner.')
    w('')
    OUT.write_text('\n'.join(L) + '\n')
    print('wrote', OUT.name)
    return 0


if __name__ == '__main__':
    sys.exit(main())
