"""Generates REPORT.md (tables and text) from results/*.json of the altloc-tie repair. No number is typed here.

    .venv/bin/python benchmarks/audit/structpair_altloc_tie_repair_2026-10-26/make_report.py
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE / "results"
rep = json.loads((R / "replay_summary.json").read_text())
ba = json.loads((R / "repair_before_after.json").read_text())
dg = json.loads((R / "btk2_precision_diagnosis.json").read_text())


def table(rows, head):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


rows = []
for p in rep["pairs"]:
    o = p["optional_sensitivity"]
    before = "refused (exit 2): " + p["original_stderr"].replace("input error: rejected: ", "")[:70] if p["original_stderr"] else "completed (sensitivity computed or not applicable)"
    after_sens = o["status"] if o["status"] != "computed" else "computed; largest changes " + ", ".join(f"{k} {v:.1e}" for k, v in o["max_abs_change"].items() if v is not None)[:60]
    rows.append([p["pair_id"], p["frozen_primary_outcome"], before, "completed" if p["primary_execution"]["returncode"] == 0 else "refused",
                 "yes" if all(p["primary_outputs_byte_identical_to_reference"].values()) and p["summary_equal_except_altloc_sensitivity"] else "NO",
                 after_sens, f"{o['n_ties']} in {', '.join(o['structures_with_ties']) or 'none'}"])
t1 = table(rows, ["pair", "KIN-PAIR-1 frozen outcome (unchanged)", "before the repair (original primary run)", "after: primary execution", "primary outputs identical to the earlier run without the optional entry",
                  "after: optional sensitivity", "tied residues (structures)"])
c = rep["counts"]
tt = table([["tests of the repair (tests/test_structpair_altloc_ties.py)", f"{ba['counts']['before']['passed']} passed, {ba['counts']['before']['failed']} failed", f"{ba['counts']['after']['passed']} passed, {ba['counts']['after']['failed']} failed"]],
           ["", "old code (commit before the repair)", "repaired code"])
b = dg["btk2"]
s = b["serialized"]
pre = b["preformat_at_the_same_value"]
text = f"""# structpair optional altloc-sensitivity tie repair (KNOWN_ISSUES m13): generated report

Generated by `make_report.py` from `results/*.json`. Design (written before the implementation): `DESIGN.md`. **Engineering regression, not a new evaluation:** KIN-PAIR-1 keeps its frozen-rule outcome (IMPLEMENTATION FAILURE) and all its files; the replay below only re-runs its six original specifications.

## Behaviour after the repair (structpair 0.3.1)

A tie met only by the optional `altloc_sensitivity: highest_occupancy` no longer aborts the run: the primary comparison is completed and written unchanged, and the sensitivity is reported as **unavailable, not zero**, with every tied residue (structure, chain, residue, insertion code, whether it is in the correspondence, alternate locations, occupancies). No partial value is given, because a partial value needs a new rule for the tied residues and would change the windows around them and the global fit. A tie under the PRIMARY policy keeps its explicit refusal. Every other error is passed through unchanged.

## Before and after on the six KIN-PAIR-1 specifications (original specs, optional request kept)

{t1}

*Table 1. Purpose: show what the repair changes for the six original specifications and what it does not. Primary execution and optional-sensitivity availability are separate columns; "unavailable" is not counted as a sensitivity result. Limitation: the same six pairs that exposed the defect (regression, not an evaluation). Source: `results/replay_summary.json`.*

Primary execution completed for {c['primary_execution_completed']} of {c['pairs']} pairs ({c['primary_execution_refused']} refused). Optional sensitivity: computed for {c['optional_sensitivity_computed']}, not applicable for {c['optional_sensitivity_not_applicable']}, unavailable for {c['optional_sensitivity_unavailable']}.

{tt}

Failing before and passing after: {len(ba['failed_before_and_passing_after'])} tests; passing in both: {len(ba['passing_before_and_after'])} (no alternate locations, unique highest occupancy, primary tie still refused, unrelated error not swallowed).

## BTK-2 precision diagnosis (KIN-PAIR-1 supplement, invariance deviation {s['max_serialized_deviation']!r} against 1e-4)

The deviation sits at `{s['location']['column']}` position {s['location']['position']}: the two CSV strings are `{s['location']['base_text']}` and `{s['location']['moved_text']}`; their exact decimal difference is {s['exact_decimal_difference_of_the_two_strings']}, one CSV quantum ({s['csv_quantum_at_this_magnitude_6_significant_figures']:g}, because values of 10 to 100 carry 6 significant figures). The floating-point subtraction of the two parsed strings gives {s['float_difference_repr']}, which exceeds 1e-4 by {s['float_difference_minus_tolerance']:.1e}.

| Stage | Quantity | Value |
|---|---|---|
| Input text | independent float64 recomputation from the PDB text, original vs moved copy (max over all windows) | {b['independent_float64_from_text_max_deviation']:.1e} |
| Adapter storage | float32 coordinate spacing at the largest coordinates ({b['float32_coordinate_storage']['moved']['max_abs_coordinate_angstrom']:.0f} Å) | {b['float32_coordinate_storage']['moved']['float32_spacing_at_that_magnitude_angstrom']:.1e} |
| Computation, same value before formatting | base {pre['base_preformat']!r} vs moved {pre['moved_preformat']!r} | {pre['preformat_difference']:.1e} |
| Computation, any metric before formatting | largest base-vs-moved difference | {b['preformat_max_deviation_any_metric']:.1e} |
| Output rounding | the two values format to `{pre['base_formatted']}` and `{pre['moved_formatted']}` | {s['max_serialized_deviation'] - 0:.6e} |
| Threshold comparison | serialized difference minus tolerance | {s['float_difference_minus_tolerance']:.1e} |

*Table 2. Purpose: trace the BTK-2 value from input to comparison. Limitation: one pair; the synthetic control ({dg['synthetic_control']['max_preformat_deviation']:.1e} before and {dg['synthetic_control']['max_serialized_deviation']:.1e} after formatting; below 1e-4 because its values are under 10 Å) shows the same mechanism at a smaller quantum. Source: `results/btk2_precision_diagnosis.json`.*

**Source established:** the unformatted values differ by at most {b['preformat_max_deviation_any_metric']:.1e}, far below the tolerance. The input and the rigid motion are exact in float64 ({b['independent_float64_from_text_max_deviation']:.0e}); the difference that exists before formatting comes from the adapter holding coordinates as float32 (moved coordinates are larger, up to {b['float32_coordinate_storage']['moved']['max_abs_coordinate_angstrom']:.0f} Å). That {pre['preformat_difference']:.1e} difference straddles a rounding boundary of the 6-significant-figure CSV (10.28395), so the serialized values differ by one quantum of {s['csv_quantum_at_this_magnitude_6_significant_figures']:g}; the comparison of that quantum with the 1e-4 tolerance is then decided by floating-point noise ({s['float_difference_minus_tolerance']:.1e}). The frozen tolerance and all historical results are unchanged; the CSV format is not changed here. A change to output precision needs its own justified task.
"""
(HERE / "REPORT.md").write_text(text)
print("wrote REPORT.md")
