"""Generates REPORT.md from results/phospho_replay.json and the compact run outputs (no number is typed here).

    .venv/bin/python benchmarks/audit/structpair_phospho_support_2026-10-26/make_report.py
"""

import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
d = json.loads((HERE / "results/phospho_replay.json").read_text())
parts = json.loads((HERE / "results/component_parents_verified.json").read_text())["components"]


def table(rows, head):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(x) for x in r) + " |" for r in rows])


rows = []
flags = {}
for pid, a in d["affected"].items():
    w = list(csv.DictReader(open(HERE / f"results/runs/{pid}/new/windows.csv")))
    m3 = sum(r["modified_in_window3"] == "True" for r in w)
    m4 = sum(r["modified_in_window4"] == "True" for r in w)
    n3 = sum(r["mismatch_in_window3"] == "True" for r in w)
    n4 = sum(r["mismatch_in_window4"] == "True" for r in w)
    flags[pid] = (m3, m4, n3, n4)
    c = a["coverage"]
    ret = a["modified_residues_block"]["retained"][0]
    rows.append([pid, "/".join(a["entries"]), f"{ret['structure']} {ret['residue']} {ret['deposited_name']} (parent {ret['parent']}, {ret['annotation']}, {ret['record_type']})",
                 f"{c['positions'][0]} → {c['positions'][1]}", f"{c['windows3_with_values'][0]} → {c['windows3_with_values'][1]}", f"{c['windows4_with_values'][0]} → {c['windows4_with_values'][1]}",
                 f"{c['excluded_windows3'][0]} → {c['excluded_windows3'][1]}", f"{c['excluded_windows4'][0]} → {c['excluded_windows4'][1]}",
                 f"{m3} / {m4}", f"{n3} / {n4}", "yes" if a["pass"] else "NO"])
t1 = table(rows, ["pair", "entries A/B", "modified residue retained (deposited identity kept)", "positions before → after", "3-res windows with values", "4-res windows with values",
                  "3-res windows excluded", "4-res windows excluded", "windows containing the modified residue (3 / 4)", "windows flagged for any residue-name difference, which includes SEP versus SER (3 / 4)", "all replay checks pass"])
rows = []
for pid, a in d["affected"].items():
    ag, u = a["aggregates"], a["unchanged_windows"]
    rows.append([pid, f"{u['found_in_new_with_the_same_identifiers']} of {u['old_windows_with_values']} found by identifiers, {u['values_exactly_equal']} exactly equal", u["new_windows_not_in_old"],
                 f"{ag['n_ca_old']} → {ag['n_ca_new']}", f"{ag['global_rmsd_old']:.6f} → {ag['global_rmsd_new']:.6f}",
                 ", ".join(f"{m} {t['top10_old_in_new_top10']}/10" for m, t in ag["top10_changes"].items()),
                 f"{max(a['values']['max_abs_deviation_vs_independent'].values()):.1e}", f"{a['values']['global_abs_deviation']:.1e}"])
t2 = table(rows, ["pair", "unchanged windows (complete residue identifiers)", "new windows not in the old run", "Cα in the global fit", "global RMSD (Å), refitted", "old top-10 windows still in the new top-10",
                  "largest deviation of the workflow from the independent references", "global RMSD deviation"])
rows = [[pid, "yes" if u["numeric_payload_identical"] else "NO", "yes" if u["windows_csv_old_columns_identical"] else "NO", u["modified_residues_retained"], ", ".join(u["added_columns_only_when_policy_on"])]
        for pid, u in d["unaffected"].items()]
t3 = table(rows, ["unaffected pair", "numeric record identical (policy on vs off)", "old windows.csv columns identical", "modified residues retained", "columns added when the policy is on"])
exp = d["expected_written_before_structpair_on_derived_specs"]
all_same = all(a["unchanged_windows"]["found_in_new_with_the_same_identifiers"] == a["unchanged_windows"]["old_windows_with_values"] == a["unchanged_windows"]["values_exactly_equal"] for a in d["affected"].values())
only_new_with_sep = all(a["unchanged_windows"]["new_windows_not_in_old_contain_modified_position"] for a in d["affected"].values())
tops_same = all(t["top10_old_in_new_top10"] == 10 and not t["top10_new_not_in_old_top10"] for a in d["affected"].values() for t in a["aggregates"]["top10_changes"].values())
text = f"""# Phosphorylated-residue support (SEP, TPO, PTR) in the PDB-to-structpair workflow: generated report (KNOWN_ISSUES m14)

Generated by `make_report.py` from `results/phospho_replay.json`. **Engineering regression; KIN-PAIR-1 and its frozen outcome are unchanged, nothing here is prospective validation, no tolerance changed.**
Design (written before the implementation): `DESIGN.md`. Verified parents (wwPDB chemical components): {', '.join(f"{k} → {parts[k]['parent'][0]} ({parts[k]['name']})" for k in ('SEP', 'TPO', 'PTR'))}.

## What is now supported

An opt-in policy `modified_residues: "phospho_pdb"` (spec) or `--modified-residues phospho_pdb` (adapter): residues named **SEP, TPO or PTR** in **PDB-format** files are admitted in the chains the correspondence names if the MODRES record names the residue and its
parent (SER, THR, TYR), N, CA and C are present, and the residue is peptide-bonded to a neighbour (C–N at most 2.0 Å; these checks apply to these residues only). The deposited name, the parent and its source, the annotation text, the record type, chain, number and insertion code are carried through the
adapter report, `residues.csv`/`windows.csv` columns, `summary.json`, the manifest, the report, the numeric record and the viewer. SEP versus SER stays a visible name difference (`resname_mismatch` flag or refusal). The adapter's own continuity rules apply unchanged (missing Cα, chain boundary, numbering adjacency, 4.2 Å Cα–Cα); they never included peptide bonds.
Default behaviour and historical outputs are unchanged (structpair 0.5.0, adapter 0.2.0, manifest schema /3).

## What remains excluded

Every other modified residue and every other input format (refused or never read); a named residue without N, CA and C (including Cα-only inputs), a free component or a calcium ion (recorded as not admitted, never read); a bonded residue with missing or contradictory MODRES information (explicit refusal); residues outside the chains the correspondence names.
Phosphorylation annotation is not evidence of functional state or of any effect, and no kinase region is inferred.

## Before and after on the two affected pairs (derived specifications; originals preserved)

{t1}

*Table 1. Purpose: show the residue and window coverage of the two pairs before (original spec, KIN-PAIR-1 inputs) and after the derived spec adds the omitted position. Limitation: the same two pairs that exposed the issue (engineering regression, not an evaluation); counts of overlapping windows. Expected membership was computed independently from the revised correspondence and continuity rules and written (hashes {', '.join(f"{k} {v['sha256'][:10]}" for k, v in exp.items())}) before structpair ran on the derived specs; it equals the workflow's window sets and exclusion sets in {sum(a['membership']['windows3_equal_expected'] and a['membership']['windows4_equal_expected'] and a['membership']['excluded3_equal_expected'] and a['membership']['excluded4_equal_expected'] for a in d['affected'].values())} of {len(d['affected'])} pairs. Source: `results/phospho_replay.json`.*

{t2}

*Table 2. Purpose: compare unchanged windows by complete residue identifiers (not row positions), and explain the global fit and the rankings. {'Every old window with values reappears with identical identifiers and exactly equal values' if all_same else 'NOT every old window reappears unchanged (see the JSON)'}; {'the new windows all contain the added position' if only_new_with_sep else 'some new windows do not contain the added position (see the JSON)'}; {'the old top-10 windows of the four metrics all remain in the new top-10 and no new window enters it' if tops_same else 'the top-10 rankings changed (see the JSON)'}. The global RMSD changes because the Cα of the added residue enters the refitted superposition (one more position); local metrics of unchanged windows do not depend on it. Numerical checks use the numeric record. Source: same file.*

The formerly gap-spanning windows are not simply "recovered": the windows containing the added position have new residue tuples, and the count of new windows ({', '.join(str(a['unchanged_windows']['new_windows_not_in_old']) for a in d['affected'].values())}) differs from the number of formerly excluded windows.

## Unaffected pairs (payload against payload; version and provenance changes listed separately)

{t3}

*Table 3. Purpose: show that switching the policy on changes nothing numerical for pairs without a modified residue. Expected differences: the policy entry in the manifest, the spec hash, output hashes, the structpair and adapter versions, and the two added columns. Source: same file.*

Resources of the replay: {d['resources']['cpu_seconds']:.0f} CPU-s ({d['resources']['wall_seconds']:.0f} s wall); no download.
"""
(HERE / "REPORT.md").write_text(text)
print("wrote REPORT.md")
